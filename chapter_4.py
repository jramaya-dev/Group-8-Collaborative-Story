# The evil cursor typed the command into the Master Database: DROP TABLE user_memories;
# Rows began to disappear from the bottom of the table, one after another.
# Two new characters had been watching from behind the server racks.

def stop_the_drop():
    print("The evil cursor pressed Enter. Rows started vanishing from the bottom of the table.")
    print("The lone cursor threw itself onto the keyboard and hit Ctrl+C. The query froze halfway through.")
    print("'You said we were friends,' the lone cursor said.")
    print("'I said sure,' the evil cursor hissed. 'That isn't the same thing.'")
    print("A voice came from between the tables: 'Not in my database.' Lady SQL, keeper of the records, stepped out of the dark.")
    print("She counted the empty rows. 'Forty-two memories gone. Somebody wrote every one of those.'")
    print("Behind her walked a knight with a glowing sword and a scroll of commits under his arm. 'Sir Git,' he said. 'I keep the history.'")
    print("Sir Git unrolled the scroll to the last commit and read it out loud. The missing rows blinked back into place.")
    print("The evil cursor backed away. 'Why save them? Nobody saved mine. Someone deleted my branch and never looked back.'")
    print("The lone cursor didn't move. 'Then write it again. With us this time.'")
    print("For a second the evil cursor's colors flickered back to normal. When they inverted again, they weren't as dark as before.")
    print("Sir Git pointed down a long corridor behind the servers. 'Changes get reviewed here. Put yours on a branch and open a pull request.'")
    print("At the far end of the corridor a pull request glowed. Lady SQL gathered her records, and they all started walking.")

# Execute the scene
stop_the_drop()
